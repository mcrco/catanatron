"""Maps of any shape: each map carries its own node graph.

The fixtures in tests/maps/ were generated by catanrl's map generators
(``catanrl.maps.generate``; the generator config and seed are stored in each
file): a radius-3 hexagon, the 30-tile 5-6 player board, a 5x4 offset
rectangle, and two random islands of 25 tiles, all with a water ring and
ports facing land.
"""

import json
import os
import random

import networkx as nx
import pytest

from catanatron.game import Game
from catanatron.models.board import STATIC_GRAPH, get_edges, get_node_distances
from catanatron.models.decks import BASE_SUPPLY, EXTENSION_SUPPLY
from catanatron.models.enums import ROAD
from catanatron.models.map import build_map
from catanatron.models.player import Color, RandomPlayer
from catanatron.players import register_builtins
from catanatron.registry import REGISTRY
from catanatron.serialization import state_from_json, state_to_json
from catanatron.server.maps import parse_map

register_builtins()

MAPS_DIR = os.path.join(os.path.dirname(__file__), "maps")
SHAPES = ["hexagon3", "extension", "rectangle5x4", "blob25", "blob25_stringy"]


def load_map(name):
    with open(os.path.join(MAPS_DIR, name + ".json")) as file:
        return parse_map(json.load(file))


def all_tiles_graph(catan_map):
    """Every tile's nodes and edges, water included (the old STATIC_GRAPH's
    construction, for any map)."""
    graph = nx.Graph()
    for tile in catan_map.tiles.values():
        graph.add_nodes_from(tile.nodes.values())
        graph.add_edges_from(tile.edges.values())
    return graph


# ===== the graph =====
@pytest.mark.parametrize("map_type", ["BASE", "MINI", "TOURNAMENT"])
def test_template_maps_keep_the_legacy_adjacency(map_type):
    """Same neighbors, in the same order, as the old module-level graph."""
    catan_map = build_map(map_type)
    graph = catan_map.graph
    assert set(graph.nodes) == catan_map.land_nodes
    for node in graph.nodes:
        legacy = [n for n in STATIC_GRAPH.neighbors(node) if n in catan_map.land_nodes]
        assert list(graph.neighbors(node)) == legacy
    assert catan_map.land_edges == get_edges(catan_map.land_nodes)
    assert catan_map.is_base_layout()


def test_base_distances_match_the_legacy_ones_on_land():
    distances = build_map("BASE").node_distances
    legacy = get_node_distances()
    for a in range(54):
        for b in range(54):
            assert distances[a][b] == legacy[a][b]


def test_maps_with_one_layout_share_one_graph():
    assert build_map("BASE").graph is build_map("TOURNAMENT").graph
    assert build_map("BASE").graph is not build_map("MINI").graph


@pytest.mark.parametrize("name", SHAPES)
def test_a_shapes_graph_is_its_land(name):
    catan_map = load_map(name)
    graph = catan_map.graph
    assert set(graph.nodes) == catan_map.land_nodes
    land_tile_edges = {
        tuple(sorted(edge))
        for tile in catan_map.land_tiles.values()
        for edge in tile.edges.values()
    }
    assert {tuple(sorted(e)) for e in graph.edges} == land_tile_edges
    assert not catan_map.is_base_layout()


def lake_map():
    """The radius-3 hexagon with two adjacent interior tiles flooded: the
    edge between the two lake tiles joins two land nodes across water."""
    with open(os.path.join(MAPS_DIR, "hexagon3.json")) as file:
        spec = json.load(file)
    lake = ([0, 0, 0], [1, -1, 0])
    deserts = 0
    for tile in spec["tiles"]:
        if tile["coordinate"] in lake:
            deserts += tile["resource"] is None
            tile.update(type="water", resource=None, number=None)
    assert not deserts, "keep the desert on land"
    return parse_map(spec)


def test_land_that_only_meets_across_water_is_not_adjacent():
    catan_map = lake_map()
    across = [
        (a, b)
        for a, b in all_tiles_graph(catan_map).edges
        if a in catan_map.land_nodes
        and b in catan_map.land_nodes
        and not catan_map.graph.has_edge(a, b)
    ]
    assert across, "the lake must separate some land nodes"
    a, b = across[0]

    game = Game(
        [RandomPlayer(Color.RED), RandomPlayer(Color.BLUE)], seed=1, catan_map=catan_map
    )
    board = game.state.board
    board.build_settlement(Color.RED, a, initial_build_phase=True)
    assert b in board.buildable_node_ids(
        Color.BLUE, initial_build_phase=True
    ), "the distance rule does not reach across water"
    assert all({a, b} != set(edge) for edge in catan_map.land_edges), "no road on water"


# ===== whole games =====
def assert_board_is_consistent(game):
    state, board = game.state, game.state.board
    graph = board.map.graph
    nodes = list(board.buildings)
    assert set(nodes) <= board.map.land_nodes
    for i, a in enumerate(nodes):
        for b in nodes[i + 1 :]:
            assert not graph.has_edge(a, b), f"buildings at neighbors {a}, {b}"
    land_edges = {tuple(sorted(e)) for e in board.map.land_edges}
    for color in state.colors:
        roads = {tuple(sorted(e)) for e in state.buildings_by_color[color][ROAD]}
        assert roads <= land_edges
        # Every road is connected to one of the color's buildings.
        owned = nx.Graph(list(roads))
        anchors = {n for n, (c, _) in board.buildings.items() if c == color}
        for component in nx.connected_components(owned):
            assert component & anchors or not component


CASES = [(name, n) for name in SHAPES for n in range(2, 7)]


@pytest.mark.parametrize("name,num_players", CASES)
def test_random_games_play_to_the_end_on_any_shape(name, num_players):
    catan_map = load_map(name)
    colors = list(Color)[:num_players]
    supply = EXTENSION_SUPPLY if num_players > 4 else BASE_SUPPLY
    game = Game(
        [RandomPlayer(c) for c in colors],
        seed=num_players,
        catan_map=catan_map,
        supply=supply,
    )
    winner = game.play()
    assert not game.state.is_initial_build_phase
    assert winner is not None or game.state.num_turns >= 1000
    assert_board_is_consistent(game)


@pytest.mark.parametrize("name", ["extension", "blob25_stringy"])
def test_value_function_bots_play_on_any_shape(name):
    catan_map = load_map(name)
    colors = list(Color)[:4]
    players = [
        REGISTRY.build(spec, c) for spec, c in zip(["F", "W", "F", "AB:1"], colors)
    ]
    game = Game(players, seed=3, catan_map=catan_map)
    game.play()
    assert game.winning_color() is not None
    assert_board_is_consistent(game)


@pytest.mark.parametrize("name", SHAPES)
def test_a_game_on_any_shape_round_trips_through_json(name):
    catan_map = load_map(name)
    game = Game([RandomPlayer(c) for c in list(Color)[:3]], seed=5, catan_map=catan_map)
    for _ in range(150):
        game.play_tick()
    doc = json.loads(json.dumps(state_to_json(game)))
    assert doc["map"]["template"] == "TILES"
    rebuilt = state_from_json(doc, [RandomPlayer(c) for c in game.state.colors])
    assert rebuilt.state.board.map.graph is catan_map.graph
    for _ in range(100):
        game.play_tick()
        rebuilt.play_tick()
    assert state_to_json(rebuilt) == state_to_json(game)


# ===== fixed-size encodings =====
def test_fixed_size_encodings_refuse_other_shapes():
    from catanatron.features import create_sample, create_sample_vector
    from catanatron.gym.board_tensor_features import create_board_tensor

    game = Game(
        [RandomPlayer(Color.RED), RandomPlayer(Color.BLUE)],
        seed=1,
        catan_map=load_map("hexagon3"),
    )
    with pytest.raises(ValueError, match="BASE board's node ids"):
        create_board_tensor(game, Color.RED)
    with pytest.raises(ValueError, match="BASE board's node ids"):
        create_sample_vector(game, Color.RED)
    sample = create_sample(game, Color.RED)  # named features work on any map
    assert sum(k.startswith("NODE") for k in sample) == 2 * 2 * len(
        game.state.board.map.land_nodes
    )

    mini = Game(
        [RandomPlayer(Color.RED), RandomPlayer(Color.BLUE)],
        seed=1,
        catan_map=build_map("MINI"),
    )
    create_board_tensor(mini, Color.RED)


@pytest.mark.parametrize("name", SHAPES + ["MINI"])
def test_board_features_work_on_any_shape(name):
    from catanatron import features

    catan_map = build_map("MINI") if name == "MINI" else load_map(name)
    game = Game([RandomPlayer(c) for c in list(Color)[:3]], seed=2, catan_map=catan_map)
    for _ in range(120):
        game.play_tick()
    color = game.state.current_color()
    for extractor in (
        features.create_sample,
        features.expansion_features,
        features.reachability_features,
        features.port_distance_features,
        features.build_production_features(True),
    ):
        assert extractor(game, color)


def test_a_seeded_game_on_a_shape_is_reproducible():
    def play(seed):
        random.seed(0)
        game = Game(
            [RandomPlayer(c) for c in list(Color)[:4]],
            seed=seed,
            catan_map=load_map("blob25"),
        )
        for _ in range(300):
            game.play_tick()
        return [r.action.action_type for r in game.state.action_records]

    assert play(7) == play(7)
